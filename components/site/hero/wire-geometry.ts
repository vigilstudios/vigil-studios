/** Three.js's default XYZ Euler rotation, stored as rows. */
export function wireRotation(x: number, y: number, z: number) {
  const a = Math.cos(x), b = Math.sin(x), c = Math.cos(y), d = Math.sin(y), e = Math.cos(z), f = Math.sin(z);
  return [c * e, -c * f, d, a * f + b * e * d, a * e - b * f * d, -b * c, b * f - a * e * d, b * e + a * f * d, a * c];
}

/** Same perspective projection as the original camera at (0, 0, 16), FOV 30. */
export function projectWireVertex(vertices: ArrayLike<number>, offset: number, m: readonly number[], scale: number, tx: number, ty: number, width: number, height: number, focal: number): [number, number] {
  const x = vertices[offset], y = vertices[offset + 1], z = vertices[offset + 2];
  const rx = (m[0] * x + m[1] * y + m[2] * z) * scale + tx;
  const ry = (m[3] * x + m[4] * y + m[5] * z) * scale + ty;
  const depth = 16 - (m[6] * x + m[7] * y + m[8] * z) * scale;
  return [width / 2 + rx * focal / depth, height / 2 - ry * focal / depth];
}
