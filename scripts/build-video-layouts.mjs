import fs from 'node:fs';
import {execFileSync} from 'node:child_process';
import postcss from 'postcss';
const files = execFileSync('git',['ls-files','design-engine/**/*.css','components/ui/media-galleries.css'],{encoding:'utf8'}).trim().split('\n').filter(file=>!file.includes('/preview/')&&!file.includes('/media/'));
const output = postcss.root();
for(const file of files){
  // Use the committed stylesheet baseline so unrelated local experiments never enter the release.
  const source=execFileSync('git',['show',`HEAD:${file}`],{encoding:'utf8'});
  const root=postcss.parse(source);
  function extract(parent){
    const result=[];
    for(const node of parent.nodes??[]){
      if(node.type==='rule' && /(?<![\w-])(img|picture)(?![\w-])/.test(node.selector)){
        result.push(node.clone({selector:node.selector.replace(/(?<![\w-])img(?![\w-])/g,'video').replace(/(?<![\w-])picture(?![\w-])/g,'.de-video')}));
      }else if(node.type==='atrule'&&node.nodes){
        const children=extract(node);if(children.length){const clone=node.clone();clone.removeAll();clone.append(children);result.push(clone);}
      }
    }
    return result;
  }
  const rules=extract(root);if(rules.length){output.append(postcss.comment({text:`Video geometry mirrors ${file}`}));output.append(rules);}
}
fs.writeFileSync('design-engine/media/video-layouts.css',`/* Generated by scripts/build-video-layouts.mjs. Existing image CSS is untouched. */\n${output.toString()}\n`);
console.log(`Generated native video geometry from ${files.length} production stylesheets.`);
